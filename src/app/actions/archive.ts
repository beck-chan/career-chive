function isoDate(value: string | null | undefined) {
  if (!value) return "";
  const raw = String(value).trim();
  const match = /^(\d{4}-\d{2}-\d{2})/.exec(raw);
  return match ? match[1] : raw.slice(0, 10);
}

const PAGE_SIZE = 1000;

async function fetchAllRows<T>(
  makeQuery: () => {
    range: (
      from: number,
      to: number,
    ) => PromiseLike<{ data: T[] | null; error: { message: string } | null }>;
  },
): Promise<T[]> {
  const rows: T[] = [];
  for (let from = 0; ; from += PAGE_SIZE) {
    const { data, error } = await makeQuery().range(
      from,
      from + PAGE_SIZE - 1,
    );
    if (error) throw error;
    const chunk = data ?? [];
    rows.push(...chunk);
    if (chunk.length < PAGE_SIZE) break;
  }
  return rows;
}

function mapOrg(row: OrgRow): Org {
  return {
    id: row.id,
    name: row.name,
    dateActive: isoDate(row.date_active),
    dateInactive: isoDate(row.date_inactive),
    hidden: Boolean(row.hidden),
    autoGenerateDays: [...(row.auto_generate_days ?? [1, 2, 3, 4, 5])],
  };
}

function orgWrite(org: Org) {
  return {
    id: org.id,
    name: org.name,
    date_active: org.dateActive || null,
    date_inactive: org.dateInactive || null,
    hidden: org.hidden,
    auto_generate_days: org.autoGenerateDays,
  };
}

function mapWork(row: WorkDbRow): WorkRow {
  return {
    id: row.id,
    title: row.title ?? "",
    description: row.description ?? "",
    link: row.link ?? "",
  };
}

function mapArtifact(row: CitationRow): ArtifactRow {
  return {
    id: row.id,
    title: row.title ?? "",
    url: row.url ?? "",
    attachment: row.attachment ?? "",
    attachmentKey: row.attachment_key ?? "",
  };
}

async function gatedClient() {
  await requireSession();
  if (!isSupabaseConfigured()) return { client: null as SupabaseClient | null, missing: true };
  const client = createAdminClient();
  if (!client) return { client: null, missing: true };
  return { client, missing: false };
}

async function loadPasswordHash(client: SupabaseClient) {
  const { data, error } = await client
    .from("settings")
    .select("password_hash")
    .eq("id", 1)
    .maybeSingle();
  if (error) throw error;
  return (data as { password_hash?: string } | null)?.password_hash ?? "";
}

async function confirmPassword(client: SupabaseClient, password: string) {
  if (!password.trim()) return false;
  const hash = await loadPasswordHash(client);
  if (!hash) return true;
  return verifyPassword(password, hash);
}

export async function loadArchive(options?: {
  ensure?: boolean;
}): Promise<ActionResult<ArchiveSnapshot> & { data: ArchiveSnapshot }> {
  if (!(await supabaseConnectionOk())) {
    return noDatabaseConnection();
  }

  const session = await getSession();
  if (flags.private && !session) {
    return {
      ok: false,
      error: "Not signed in.",
      signedOut: true,
      data: emptySnapshot(),
    };
  }

  const client = createAdminClient();
  if (!client) {
    return noDatabaseConnection();
  }

  try {
    if (options?.ensure !== false) {
      await client.rpc("ensure_generated_days");
    }

    const [settingsRes, orgsRes, dayRows, workRows, citationRows] =
      await Promise.all([
        client
          .from("settings")
          .select("username, password_hash, password_encrypted, archive_start_date, autogenerate_start_date, timezone")
          .eq("id", 1)
          .maybeSingle(),
        client
          .from("organizations")
          .select("id, name, date_active, date_inactive, hidden, auto_generate_days"),
        fetchAllRows<DayRow>(() =>
          client
            .from("days")
            .select(
              "id, organization_id, work_date, attendance, notes, rating, comments",
            )
            .order("id"),
        ),
        fetchAllRows<WorkDbRow>(() =>
          client
            .from("work")
            .select("id, day_id, title, description, link, position")
            .order("position")
            .order("id"),
        ),
        fetchAllRows<CitationRow>(() =>
          client
            .from("citations")
            .select(
              "id, day_id, title, url, attachment, attachment_key, position",
            )
            .order("position")
            .order("id"),
        ),
      ]);

    if (settingsRes.error) throw settingsRes.error;
    if (orgsRes.error) throw orgsRes.error;

    const settingsRow = (settingsRes.data ?? null) as SettingsRow | null;
    const orgs = ((orgsRes.data ?? []) as OrgRow[]).map(mapOrg);

    const workByDay = new Map<string, WorkRow[]>();
    const workSorted = [...workRows].sort(
      (a, b) =>
        (a.position ?? 0) - (b.position ?? 0) || a.id.localeCompare(b.id),
    );
    for (const row of workSorted) {
      const list = workByDay.get(row.day_id) ?? [];
      list.push(mapWork(row));
      workByDay.set(row.day_id, list);
    }
    const artifactsByDay = new Map<string, ArtifactRow[]>();
    const citationSorted = [...citationRows].sort(
      (a, b) =>
        (a.position ?? 0) - (b.position ?? 0) || a.id.localeCompare(b.id),
    );
    for (const row of citationSorted) {
      const list = artifactsByDay.get(row.day_id) ?? [];
      list.push(mapArtifact(row));
      artifactsByDay.set(row.day_id, list);
    }

    const days: Record<string, Record<string, DayEntry>> = {};
    for (const row of dayRows) {
      const iso = isoDate(row.work_date);
      if (!days[row.organization_id]) days[row.organization_id] = {};
      days[row.organization_id][iso] = {
        attendance: parseAttendance(row.attendance),
        notes: row.notes ?? "",
        rating: row.rating ?? null,
        comments: row.comments ?? "",
        work: workByDay.get(row.id) ?? [],
        artifacts: artifactsByDay.get(row.id) ?? [],
      };
    }

    return {
      ok: true,
      data: {
        settings: {
          archiveStartDate: isoDate(settingsRow?.archive_start_date),
          autogenerateStartDate: isoDate(settingsRow?.autogenerate_start_date),
          timezone: normalizeTimeZone(settingsRow?.timezone),
          username: settingsRow?.username ?? "",
          password: decryptPassword(settingsRow?.password_encrypted),
          hasPassword: Boolean(settingsRow?.password_hash?.trim()),
          orgs,
        },
        days,
      },
    };
  } catch (error) {
    const message = error instanceof Error ? error.message : "No database connection.";
    return {
      ok: false,
      error: message,
      connection: true,
      data: emptySnapshot(),
    };
  }
}

async function loadArchiveStart(client: SupabaseClient) {
  const { data, error } = await client
    .from("settings")
    .select("archive_start_date, timezone")
    .eq("id", 1)
    .maybeSingle();
  if (error) throw error;
  const row = data as SettingsRow | null;
  return {
    archiveStart: isoDate(row?.archive_start_date),
    today: todayIso(new Date(), row?.timezone),
  };
}

class CreateDayWindowError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "CreateDayWindowError";
  }
}

const CREATE_DAY_WINDOW_MESSAGES = [
  BEFORE_ARCHIVE_START_MESSAGE,
  BEFORE_DATE_ACTIVE_MESSAGE,
  AFTER_DATE_INACTIVE_MESSAGE,
  FUTURE_DATE_MESSAGE,
];

function actionFailure(error: unknown, fallback: string): ActionResult {
  const message = error instanceof Error ? error.message : fallback;
  if (
    error instanceof CreateDayWindowError ||
    CREATE_DAY_WINDOW_MESSAGES.includes(message) ||
    /archive start date|date active|date inactive|in the future/i.test(
      message,
    )
  ) {
    return { ok: false, error: message };
  }
  return { ok: false, error: message, connection: true };
}

async function getDayId(
  client: SupabaseClient,
  orgId: string,
  iso: string,
  create: boolean,
) {
  const existing = await client
    .from("days")
    .select("id")
    .eq("organization_id", orgId)
    .eq("work_date", iso)
    .maybeSingle();
  if (existing.error) throw existing.error;
  if (existing.data?.id) return existing.data.id as string;
  if (!create) return null;
  const { archiveStart, today } = await loadArchiveStart(client);
  const orgRes = await client
    .from("organizations")
    .select("date_active, date_inactive")
    .eq("id", orgId)
    .maybeSingle();
  if (orgRes.error) throw orgRes.error;
  const org = orgRes.data as {
    date_active: string | null;
    date_inactive: string | null;
  } | null;
  const reason = createDayBlockReason(
    iso,
    archiveStart,
    isoDate(org?.date_active),
    isoDate(org?.date_inactive),
    today,
  );
  if (reason) throw new CreateDayWindowError(reason);
  const inserted = await client
    .from("days")
    .insert({
      organization_id: orgId,
      work_date: iso,
      attendance: null,
    })
    .select("id")
    .single();
  if (inserted.error) {
    const retry = await client
      .from("days")
      .select("id")
      .eq("organization_id", orgId)
      .eq("work_date", iso)
      .maybeSingle();
    if (retry.error) throw retry.error;
    if (retry.data?.id) return retry.data.id as string;
    throw inserted.error;
  }
  return inserted.data.id as string;
}

async function replaceDayChildren(
  client: SupabaseClient,
  dayId: string,
  day: DayEntry,
) {
  const [workRes, citationRes] = await Promise.all([
    client.from("work").select("id").eq("day_id", dayId),
    client
      .from("citations")
      .select("id, attachment_key")
      .eq("day_id", dayId),
  ]);
  if (workRes.error) throw workRes.error;
  if (citationRes.error) throw citationRes.error;

  const keepWork = new Set(day.work.map((row) => row.id));
  const keepCitations = new Set(day.artifacts.map((row) => row.id));
  const incomingArtifacts = new Map(day.artifacts.map((row) => [row.id, row]));
  const dropWork = ((workRes.data ?? []) as { id: string }[])
    .map((row) => row.id)
    .filter((id) => !keepWork.has(id));
  const existingCitations = ((citationRes.data ?? []) as {
    id: string;
    attachment_key: string | null;
  }[]);
  const dropCitations = existingCitations.filter(
    (row) => !keepCitations.has(row.id),
  );
  const staleAttachmentKeys = existingCitations
    .filter((row) => keepCitations.has(row.id))
    .map((row) => {
      const nextKey = incomingArtifacts.get(row.id)?.attachmentKey ?? "";
      const oldKey = row.attachment_key ?? "";
      return oldKey && oldKey !== nextKey ? oldKey : "";
    })
    .filter(Boolean);

  if (dropWork.length) {
    const { error } = await client.from("work").delete().in("id", dropWork);
    if (error) throw error;
  }
  if (dropCitations.length || staleAttachmentKeys.length) {
    await deleteAttachmentKeys([
      ...staleAttachmentKeys,
      ...dropCitations
        .map((row) => row.attachment_key)
        .filter((key): key is string => Boolean(key)),
    ]);
  }
  if (dropCitations.length) {
    const { error } = await client
      .from("citations")
      .delete()
      .in(
        "id",
        dropCitations.map((row) => row.id),
      );
    if (error) throw error;
  }

  if (day.work.length) {
    const { error } = await client.from("work").upsert(
      day.work.map((row, position) => ({
        id: row.id,
        day_id: dayId,
        title: row.title,
        description: row.description,
        link: row.link,
        position,
      })),
    );
    if (error) throw error;
  }

  if (day.artifacts.length) {
    const { error } = await client.from("citations").upsert(
      day.artifacts.map((row, position) => ({
        id: row.id,
        day_id: dayId,
        title: row.title,
        url: row.url,
        attachment: row.attachment,
        attachment_key: row.attachmentKey ?? "",
        position,
      })),
    );
    if (error) throw error;
  }
}

export async function saveOrganization(org: Org): Promise<ActionResult> {
  if (!org.name.trim() || !org.dateActive.trim()) {
    return { ok: false, error: "Name and Date Active are required." };
  }
  const { client, missing } = await gatedClient();
  if (missing || !client) return { ok: true };
  try {
    const { error } = await client.from("organizations").upsert(orgWrite(org));
    if (error) throw error;
    await client.rpc("ensure_generated_days");
    return { ok: true };
  } catch (error) {
    return {
      ok: false,
      error: error instanceof Error ? error.message : "Could not save organization.",
      connection: true,
    };
  }
}

export async function deleteOrganization(
  orgId: string,
  password: string,
): Promise<ActionResult> {
  const { client, missing } = await gatedClient();
  if (missing || !client) {
    return { ok: false, error: "No database connection.", connection: true };
  }
  try {
    if (!(await confirmPassword(client, password))) {
      return { ok: false, error: "Incorrect password." };
    }
    const { count, error: countError } = await client
      .from("days")
      .select("id", { count: "exact", head: true })
      .eq("organization_id", orgId);
    if (countError) throw countError;
    // Every stored day counts, including leftovers Archive will not open.
    // Bulk Clear / Delete can remove those rows. Delete stays blocked until
    // none remain.
    if (count && count > 0) {
      return { ok: false, error: "Cannot delete an organization with entries." };
    }
    const { error } = await client.from("organizations").delete().eq("id", orgId);
    if (error) throw error;
    return { ok: true };
  } catch (error) {
    return {
      ok: false,
      error: error instanceof Error ? error.message : "Could not delete organization.",
      connection: true,
    };
  }
}

