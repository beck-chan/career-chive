"use client";

import {
  useEffect,
  useLayoutEffect,
  useState,
  useSyncExternalStore,
} from "react";
import Link from "next/link";
import { usePathname, useRouter } from "next/navigation";
import { logoutAction } from "../app/actions/auth";
import { useDemo } from "../lib/demo";
import { ThemeDateField } from "./ThemeDateField";
import { LoadingBody } from "./PageStates";
import { LoginForm } from "./LoginForm";
import { ModalShell } from "./ModalShell";
import { PasswordField } from "./PasswordField";
import { flags } from "../lib/flags";
import {
  careerchiveHref,
  careerchiveOrganizationsPath,
  isCareerchiveRoute,
} from "../lib/paths";
import {
  DEFAULT_TIMEZONE,
  normalizeTimeZone,
  timeZoneOptions,
  timeZoneSelectLabel,
  todayIso,
} from "../lib/data";
import {
  DEFAULT_THEME,
  applyAppTheme,
  getThemeSnapshot,
  subscribeTheme,
  writeTheme,
} from "../lib/theme";

const TIME_ZONES = timeZoneOptions();

const NAV = [
  { route: "/", label: "Archive" },
  { route: "/overview", label: "Overview" },
  { route: "/search", label: "Search" },
  { route: "/organizations", label: "Organizations" },
] as const;

const SETTINGS_TABS = [
  { id: "timezone", label: "Time Zone" },
  { id: "archive", label: "Archive Start" },
  { id: "autogenerate", label: "Auto-generate From" },
  { id: "user", label: "Login" },
  { id: "reset", label: "Factory Reset" },
  { id: "logout", label: "Logout" },
] as const;

type SettingsTab = (typeof SETTINGS_TABS)[number]["id"];

export const OPEN_SETTINGS_EVENT = "careerchive:open-settings";

export function requestOpenSettings(tab: SettingsTab = "archive") {
  window.dispatchEvent(
    new CustomEvent(OPEN_SETTINGS_EVENT, { detail: { tab } }),
  );
}

