export { PasswordField };

export function AppChrome({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const router = useRouter();
  const {
    status,
    settings,
    factoryReset,
    updateArchiveStart,
    updateAutogenerateStart,
    updateTimezone,
    updateLogin,
  } = useDemo();
  const today = todayIso(undefined, settings.timezone);
  const signedOut = status === "signedOut";
  const chromeLocked = status === "error" || signedOut;
  const settingsHover = signedOut
    ? "Log In to Access Settings"
    : "Settings";
  const [navOpen, setNavOpen] = useState(false);
  const [navPath, setNavPath] = useState(pathname);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [draftStartDate, setDraftStartDate] = useState(
    settings.archiveStartDate,
  );
  const [draftAutogenerateDate, setDraftAutogenerateDate] = useState(
    settings.autogenerateStartDate,
  );
  const [draftTimezone, setDraftTimezone] = useState(
    normalizeTimeZone(settings.timezone),
  );
  const [savedTimezone, setSavedTimezone] = useState(
    normalizeTimeZone(settings.timezone),
  );
  const [draftUsername, setDraftUsername] = useState(settings.username);
  const [draftPassword, setDraftPassword] = useState(settings.password);
  const [syncedPassword, setSyncedPassword] = useState(settings.password);
  const [settingsTab, setSettingsTab] = useState<SettingsTab>("timezone");
  const [resetPassword, setResetPassword] = useState("");
  const [resetPhrase, setResetPhrase] = useState("");
  const [pendingReset, setPendingReset] = useState(false);
  const [pendingStartConfirm, setPendingStartConfirm] = useState<
    null | "later" | "earlier"
  >(null);
  const [pendingAutogenerateConfirm, setPendingAutogenerateConfirm] =
    useState<null | "later" | "earlier">(null);
  const [resetError, setResetError] = useState("");
  const theme = useSyncExternalStore(
    subscribeTheme,
    getThemeSnapshot,
    () => DEFAULT_THEME,
  );
  const [savedStartDate, setSavedStartDate] = useState(
    settings.archiveStartDate,
  );
  const [savedAutogenerateDate, setSavedAutogenerateDate] = useState(
    settings.autogenerateStartDate,
  );

  if (pathname !== navPath) {
    setNavPath(pathname);
    setNavOpen(false);
  }

  if (chromeLocked && settingsOpen) {
    setSettingsOpen(false);
  }

  if (settings.archiveStartDate !== savedStartDate) {
    setSavedStartDate(settings.archiveStartDate);
    setDraftStartDate(settings.archiveStartDate);
  }

  if (settings.autogenerateStartDate !== savedAutogenerateDate) {
    setSavedAutogenerateDate(settings.autogenerateStartDate);
    setDraftAutogenerateDate(settings.autogenerateStartDate);
  }

  if (normalizeTimeZone(settings.timezone) !== savedTimezone) {
    const next = normalizeTimeZone(settings.timezone);
    setSavedTimezone(next);
    setDraftTimezone(next);
  }

  if (settings.password !== syncedPassword) {
    const previous = syncedPassword;
    setSyncedPassword(settings.password);
    if (draftPassword === previous) {
      setDraftPassword(settings.password);
    }
  }

  function openSettings(tab: SettingsTab = "timezone") {
    setDraftStartDate(settings.archiveStartDate);
    setDraftAutogenerateDate(settings.autogenerateStartDate);
    setDraftTimezone(normalizeTimeZone(settings.timezone));
    setDraftUsername(settings.username);
    setDraftPassword(settings.password);
    setResetPassword("");
    setResetPhrase("");
    setPendingReset(false);
    setPendingStartConfirm(null);
    setPendingAutogenerateConfirm(null);
    setResetError("");
    setSettingsTab(
      SETTINGS_TABS.some((item) => item.id === tab) ? tab : "timezone",
    );
    setSettingsOpen(true);
  }

  function closeSettings() {
    setDraftStartDate(settings.archiveStartDate);
    setDraftAutogenerateDate(settings.autogenerateStartDate);
    setDraftTimezone(normalizeTimeZone(settings.timezone));
    setDraftUsername(settings.username);
    setDraftPassword(settings.password);
    setResetPassword("");
    setResetPhrase("");
    setPendingReset(false);
    setPendingStartConfirm(null);
    setPendingAutogenerateConfirm(null);
    setResetError("");
    setSettingsTab("timezone");
    setSettingsOpen(false);
  }

  function cancelFactoryReset() {
    setPendingReset(false);
    setResetPassword("");
    setResetPhrase("");
    setResetError("");
  }

  const canFactoryReset =
    Boolean(resetPassword.trim()) && resetPhrase === "Yes, Factory Reset";

  async function confirmFactoryReset() {
    if (!canFactoryReset) return;
    const ok = await factoryReset(resetPassword);
    if (!ok) {
      setResetError("Incorrect password.");
      return;
    }
    cancelFactoryReset();
  }

  function cancelArchive() {
    setDraftStartDate(settings.archiveStartDate);
    setPendingStartConfirm(null);
  }

  function saveArchive() {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(draftStartDate)) return;
    const previous = settings.archiveStartDate;
    if (previous && draftStartDate && draftStartDate !== previous) {
      setPendingStartConfirm(draftStartDate > previous ? "later" : "earlier");
      return;
    }
    void updateArchiveStart(draftStartDate);
  }

  function cancelStartConfirm() {
    setPendingStartConfirm(null);
  }

  function confirmStartChange() {
    setPendingStartConfirm(null);
    void updateArchiveStart(draftStartDate);
  }

  function cancelAutogenerate() {
    setDraftAutogenerateDate(settings.autogenerateStartDate);
    setPendingAutogenerateConfirm(null);
  }

  function saveAutogenerate() {
    if (!settings.archiveStartDate) return;
    const floor = settings.archiveStartDate;
    const next =
      draftAutogenerateDate && floor && draftAutogenerateDate < floor
        ? floor
        : draftAutogenerateDate;
    if (next !== draftAutogenerateDate) setDraftAutogenerateDate(next);
    const previous = settings.autogenerateStartDate;
    if (previous && next && next !== previous) {
      setPendingAutogenerateConfirm(next > previous ? "later" : "earlier");
      return;
    }
    if (!previous && next && next < today) {
      setPendingAutogenerateConfirm("earlier");
      return;
    }
    void updateAutogenerateStart(next);
  }

  function cancelAutogenerateConfirm() {
    setPendingAutogenerateConfirm(null);
  }

  function confirmAutogenerateChange() {
    if (!settings.archiveStartDate) {
      setPendingAutogenerateConfirm(null);
      return;
    }
    setPendingAutogenerateConfirm(null);
    const floor = settings.archiveStartDate;
    const next =
      draftAutogenerateDate && floor && draftAutogenerateDate < floor
        ? floor
        : draftAutogenerateDate;
    void updateAutogenerateStart(next);
  }

  function cancelTimezone() {
    setDraftTimezone(normalizeTimeZone(settings.timezone));
  }

  function saveTimezone() {
    void updateTimezone(normalizeTimeZone(draftTimezone || DEFAULT_TIMEZONE));
  }

  function cancelUser() {
    setDraftUsername(settings.username);
    setDraftPassword(settings.password);
  }

  function saveUser() {
    void updateLogin(draftUsername, draftPassword);
  }

  async function logOut() {
    await logoutAction();
    closeSettings();
    router.refresh();
  }

  useEffect(() => {
    if (!navOpen && !settingsOpen) return;
    function onKey(event: KeyboardEvent) {
      if (event.key !== "Escape") return;
      if (pendingReset) {
        cancelFactoryReset();
        return;
      }
      if (pendingStartConfirm) {
        cancelStartConfirm();
        return;
      }
      if (pendingAutogenerateConfirm) {
        cancelAutogenerateConfirm();
        return;
      }
      setNavOpen(false);
      if (settingsOpen) closeSettings();
    }
    function onPointer(event: MouseEvent) {
      const target = event.target as HTMLElement;
      if (!target.closest(".app-header")) setNavOpen(false);
    }
    function onResize() {
      if (window.innerWidth > 900) setNavOpen(false);
    }
    window.addEventListener("keydown", onKey);
    document.addEventListener("mousedown", onPointer);
    window.addEventListener("resize", onResize);
    return () => {
      window.removeEventListener("keydown", onKey);
      document.removeEventListener("mousedown", onPointer);
      window.removeEventListener("resize", onResize);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [
    navOpen,
    settingsOpen,
    settings.archiveStartDate,
    settings.username,
    pendingReset,
    pendingStartConfirm,
    pendingAutogenerateConfirm,
  ]);

  useEffect(() => {
    function onOpen(event: Event) {
      const tab = (event as CustomEvent<{ tab?: SettingsTab }>).detail?.tab;
      openSettings(tab ?? "archive");
    }
    window.addEventListener(OPEN_SETTINGS_EVENT, onOpen);
    return () => window.removeEventListener(OPEN_SETTINGS_EVENT, onOpen);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [
    settings.archiveStartDate,
    settings.autogenerateStartDate,
    settings.timezone,
    settings.username,
    settings.password,
  ]);

  useLayoutEffect(() => {
    applyAppTheme(theme);
  }, [theme]);

  return (
    <div className="app-shell">
      <header className="app-header">
        <p className="app-wordmark app-wordmark-static">
          <Wordmark />
        </p>
        <button
          type="button"
          className="app-wordmark-toggle"
          aria-expanded={navOpen}
          aria-controls="app-nav"
          onClick={() => setNavOpen((open) => !open)}
        >
          <span className="app-wordmark">
            <Wordmark />
          </span>
          <svg
            className="brand-caret"
            width="14"
            height="14"
            viewBox="0 0 24 24"
            fill="none"
            aria-hidden="true"
          >
            <path
              d="M6 9l6 6 6-6"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
            />
          </svg>
        </button>
        <nav
          id="app-nav"
          className={`app-nav${navOpen ? " is-open" : ""}`}
          aria-label="App"
        >
          {NAV.map((item) => {
            const href =
              item.route === "/organizations"
                ? careerchiveOrganizationsPath()
                : careerchiveHref(item.route);
            const active = isCareerchiveRoute(pathname, item.route);
            return (
              <Link
                key={item.route}
                href={href}
                className={active ? "is-active" : undefined}
                aria-current={active ? "page" : undefined}
              >
                {item.label}
              </Link>
            );
          })}
        </nav>
        <div className="header-action">
          <div
            className={`theme-toggle${theme === "dark" ? " is-dark" : ""}`}
            role="group"
            aria-label="Theme"
          >
            <button
              type="button"
              className={theme === "light" ? "is-active" : undefined}
              aria-pressed={theme === "light"}
              title="Light Mode"
              aria-label="Light Mode"
              onClick={() => writeTheme("light")}
            >
              <svg
                width="14"
                height="14"
                viewBox="0 0 24 24"
                fill="none"
                aria-hidden="true"
              >
                <circle
                  cx="12"
                  cy="12"
                  r="3.6"
                  stroke="currentColor"
                  strokeWidth="1.8"
                />
                <path
                  d="M12 3.2v1.7M12 19.1v1.7M4.9 4.9l1.2 1.2M17.9 17.9l1.2 1.2M3.2 12h1.7M19.1 12h1.7M4.9 19.1l1.2-1.2M17.9 6.1l1.2-1.2"
                  stroke="currentColor"
                  strokeWidth="1.8"
                  strokeLinecap="round"
                />
              </svg>
            </button>
            <button
              type="button"
              className={theme === "dark" ? "is-active" : undefined}
              aria-pressed={theme === "dark"}
              title="Dark Mode"
              aria-label="Dark Mode"
              onClick={() => writeTheme("dark")}
            >
              <svg
                width="14"
                height="14"
                viewBox="0 0 24 24"
                fill="none"
                aria-hidden="true"
              >
                <path
                  d="M16.4 3.8A8.6 8.6 0 1 0 20.2 15.2 7.1 7.1 0 0 1 16.4 3.8Z"
                  stroke="currentColor"
                  strokeWidth="1.8"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
            </button>
          </div>
          <a
            className="icon-btn docs-icon"
            href="https://career-chive.vercel.app/docs"
            target="_blank"
            rel="noopener noreferrer"
            title="Docs"
            aria-label="Docs"
          >
            <svg
              width="20"
              height="20"
              viewBox="0 0 24 24"
              fill="currentColor"
              aria-hidden="true"
            >
              <path d="M11.25 4.53A9.71 9.71 0 0 0 6 3a9.74 9.74 0 0 0-3.25.56.75.75 0 0 0-.5.7v14.25a.75.75 0 0 0 1 .71A8.24 8.24 0 0 1 6 18.75c2 0 3.82.71 5.25 1.89V4.53Zm1.5 16.1A8.21 8.21 0 0 1 18 18.75c.97 0 1.89.17 2.75.47a.75.75 0 0 0 1-.71V4.26a.75.75 0 0 0-.5-.7A9.74 9.74 0 0 0 18 3a9.71 9.71 0 0 0-5.25 1.53v16.1Z" />
            </svg>
          </a>
          <span className="settings-gear-hit" title={settingsHover}>
            <button
              type="button"
              className={`icon-btn settings-gear${chromeLocked ? " is-inert" : ""}`}
              aria-label={settingsHover}
              disabled={chromeLocked}
              onClick={() => openSettings()}
            >
              <svg
                width="20"
                height="20"
                viewBox="0 0 24 24"
                fill="currentColor"
                aria-hidden="true"
              >
                <path
                  fillRule="evenodd"
                  d="M19.14 12.94c.04-.3.06-.61.06-.94s-.02-.64-.07-.94l2.03-1.58a.49.49 0 0 0 .12-.61l-1.92-3.32a.5.5 0 0 0-.59-.22l-2.39.96c-.5-.38-1.03-.7-1.62-.94l-.36-2.54a.49.49 0 0 0-.48-.41h-3.84a.49.49 0 0 0-.47.41l-.36 2.54c-.59.24-1.13.56-1.62.94l-2.39-.96a.5.5 0 0 0-.59.22L2.74 8.87a.49.49 0 0 0 .12.61l2.03 1.58c-.05.3-.07.62-.07.94s.02.64.07.94l-2.03 1.58a.49.49 0 0 0-.12.61l1.92 3.32c.12.22.37.29.59.22l2.39-.96c.5.38 1.03.7 1.62.94l.36 2.54c.05.24.24.41.48.41h3.84c.24 0 .44-.17.47-.41l.36-2.54c.59-.24 1.13-.56 1.62-.94l2.39.96c.22.08.47 0 .59-.22l1.92-3.32a.49.49 0 0 0-.12-.61l-2.03-1.58ZM12 15.6A3.6 3.6 0 1 1 12 8.4a3.6 3.6 0 0 1 0 7.2Z"
                />
              </svg>
            </button>
          </span>
        </div>
      </header>
      <main className="app-main">
        {status === "loading" ? (
          <div className="page-cols">
            <div className="page-state-full">
              <LoadingBody />
            </div>
          </div>
        ) : signedOut ? (
          <div className="page-cols">
            <div className="page-state-full">
              <LoginForm />
            </div>
          </div>
        ) : (
          children
        )}
      </main>
      {settingsOpen ? (
        <ModalShell onClose={closeSettings}>
          <div
            className="modal settings-modal"
            role="dialog"
            aria-modal="true"
            aria-labelledby="settings-title"
          >
              <header className="settings-modal-head">
                <h2 id="settings-title" className="modal-title">
                  Settings
                </h2>
                <button
                  type="button"
                  className="icon-btn modal-close"
                  aria-label="Close"
                  onClick={closeSettings}
                >
                  <svg
                    width="18"
                    height="18"
                    viewBox="0 0 24 24"
                    fill="none"
                    aria-hidden="true"
                  >
                    <path
                      d="M6 6l12 12M18 6 6 18"
                      stroke="currentColor"
                      strokeWidth="2.1"
                      strokeLinecap="round"
                    />
                  </svg>
                </button>
              </header>
              <div
                className="day-tabs"
                role="tablist"
                aria-label="Settings sections"
              >
                {SETTINGS_TABS.filter(
                  (item) => item.id !== "logout" || flags.private,
                ).map((item) => (
                  <button
                    key={item.id}
                    type="button"
                    role="tab"
                    aria-selected={settingsTab === item.id}
                    className={settingsTab === item.id ? "is-active" : undefined}
                    onClick={() => setSettingsTab(item.id)}
                  >
                    {item.label}
                  </button>
                ))}
              </div>
              <div className="modal-fields">
                <section
                  className={`day-section${settingsTab === "timezone" ? " is-active" : ""}`}
                >
                  <h3>Time Zone</h3>
                  <p className="day-section-sub">
                    Decides what current time and today mean for this archive.
                  </p>
                  <label className="setting-field">
                    <span className="setting-label">Time Zone</span>
                    <select
                      className="app-field app-select"
                      aria-label="Time Zone"
                      value={draftTimezone}
                      onChange={(event) =>
                        setDraftTimezone(normalizeTimeZone(event.target.value))
                      }
                    >
                      {(TIME_ZONES.includes(draftTimezone)
                        ? TIME_ZONES
                        : [draftTimezone, ...TIME_ZONES]
                      ).map((zone) => (
                        <option key={zone} value={zone}>
                          {timeZoneSelectLabel(zone)}
                        </option>
                      ))}
                    </select>
                  </label>
                  <div className="day-form-actions">
                    <button
                      type="button"
                      className="text-link"
                      onClick={cancelTimezone}
                    >
                      Cancel
                    </button>
                    <button
                      type="button"
                      className="text-btn"
                      onClick={saveTimezone}
                    >
                      Update Time Zone
                    </button>
                  </div>
                </section>
                <section
                  className={`day-section${settingsTab === "archive" ? " is-active" : ""}`}
                >
                  <h3>Archive Start</h3>
                  <p className="day-section-sub">
                    Date from which the archive should show entries.
                  </p>
                  <ThemeDateField
                    className="app-date"
                    aria-label="Archive Start"
                    value={draftStartDate}
                    today={today}
                    placeholder="Select Start Date"
                    onChange={setDraftStartDate}
                  />
                  <div className="day-form-actions">
                    <button
                      type="button"
                      className="text-link"
                      onClick={cancelArchive}
                    >
                      Cancel
                    </button>
                    <button
                      type="button"
                      className="text-btn"
                      disabled={!/^\d{4}-\d{2}-\d{2}$/.test(draftStartDate)}
                      onClick={saveArchive}
                    >
                      Update Start Date
                    </button>
                  </div>
                </section>
                <section
                  className={`day-section${settingsTab === "autogenerate" ? " is-active" : ""}`}
                >
                  <h3>Auto-generate From</h3>
                  <p className="day-section-sub">
                    Date from which daily entries should be auto-generated.
                  </p>
                  <ThemeDateField
                    className="app-date"
                    aria-label="Auto-generate From"
                    value={draftAutogenerateDate}
                    min={settings.archiveStartDate || undefined}
                    today={today}
                    allowEmpty
                    disabled={!settings.archiveStartDate}
                    placeholder="Select Auto-generation Date"
                    onChange={setDraftAutogenerateDate}
                  />
                  {settings.archiveStartDate ? (
                    <p className="login-error" role="alert">
                      Leave blank to disable auto-generation of entries.
                    </p>
                  ) : (
                    <p className="login-error" role="alert">
                      Set Archive Start to enable entry auto-generation.
                    </p>
                  )}
                  <div className="day-form-actions">
                    <button
                      type="button"
                      className="text-link"
                      disabled={!settings.archiveStartDate}
                      onClick={cancelAutogenerate}
                    >
                      Cancel
                    </button>
                    <button
                      type="button"
                      className="text-btn"
                      disabled={!settings.archiveStartDate}
                      onClick={saveAutogenerate}
                    >
                      Update Auto-generation Date
                    </button>
                  </div>
                </section>
                <section
                  className={`day-section${settingsTab === "user" ? " is-active" : ""}`}
                >
                  <h3>User</h3>
                  <p className="day-section-sub">
                    Log in with these credentials in private mode.
                  </p>
                  <label className="setting-field">
                    <span className="setting-label">Username</span>
                    <input
                      className="app-field"
                      type="text"
                      autoComplete="username"
                      spellCheck={false}
                      value={draftUsername}
                      onChange={(event) =>
                        setDraftUsername(event.target.value)
                      }
                    />
                  </label>
                  <div className="setting-field">
                    <span className="setting-label">Password</span>
                    <PasswordField
                      value={draftPassword}
                      onChange={setDraftPassword}
                      hasStoredPassword={
                        settings.hasPassword && !settings.password
                      }
                    />
                  </div>
                  <div className="day-form-actions">
                    <button
                      type="button"
                      className="text-link"
                      onClick={cancelUser}
                    >
                      Cancel
                    </button>
                    <button
                      type="button"
                      className="text-btn"
                      onClick={saveUser}
                    >
                      Update Login
                    </button>
                  </div>
                </section>
                <section
                  className={`day-section${settingsTab === "reset" ? " is-active" : ""}`}
                >
                  <h3>Factory Reset</h3>
                  <p className="day-section-sub">
                    Delete all organizations and associated entries.
                  </p>
                  <div className="day-form-actions factory-reset-actions">
                    <button
                      type="button"
                      className="text-btn"
                      onClick={() => setPendingReset(true)}
                    >
                      Reset
                    </button>
                  </div>
                </section>
                {flags.private ? (
                  <section
                    className={`day-section${settingsTab === "logout" ? " is-active" : ""}`}
                  >
                    <h3>Logout</h3>
                    <p className="day-section-sub">
                      Log out of your account.
                    </p>
                    <div className="day-form-actions factory-reset-actions">
                      <button
                        type="button"
                        className="text-btn"
                        onClick={() => void logOut()}
                      >
                        Log Out
                      </button>
                    </div>
                  </section>
                ) : null}
              </div>
          </div>
        </ModalShell>
      ) : null}
      {pendingReset ? (
        <ModalShell onClose={cancelFactoryReset} stacked>
          <div
            className="modal create-entry-modal"
            role="dialog"
            aria-modal="true"
            aria-labelledby="factory-reset-title"
            aria-describedby="factory-reset-warn"
          >
            <header className="modal-head">
              <h2 id="factory-reset-title" className="modal-title">
                Factory Reset
              </h2>
              <button
                type="button"
                className="icon-btn modal-close"
                aria-label="Close"
                onClick={cancelFactoryReset}
              >
                <svg
                  width="18"
                  height="18"
                  viewBox="0 0 24 24"
                  fill="none"
                  aria-hidden="true"
                >
                  <path
                    d="M6 6l12 12M18 6 6 18"
                    stroke="currentColor"
                    strokeWidth="2.1"
                    strokeLinecap="round"
                  />
                </svg>
              </button>
            </header>
            <p id="factory-reset-warn" className="modal-permanent">
              THIS ACTION IS PERMANENT AND CANNOT BE UNDONE.
            </p>
            <p className="modal-copy">
              Delete all organizations and associated entries.
            </p>
            <div className="modal-password">
              <div className="setting-field">
                <span className="setting-label">Enter Password</span>
                <PasswordField
                  value={resetPassword}
                  onChange={(next) => {
                    setResetPassword(next);
                    if (resetError) setResetError("");
                  }}
                  focusOnMount
                  aria-label="Enter Password"
                />
                {resetError ? (
                  <p className="login-error" role="alert">
                    {resetError}
                  </p>
                ) : null}
              </div>
              <div className="setting-field">
                <span className="setting-label">
                  Type &quot;Yes, Factory Reset&quot;
                </span>
                <input
                  className="app-field"
                  type="text"
                  autoComplete="off"
                  spellCheck={false}
                  aria-label='Type "Yes, Factory Reset"'
                  value={resetPhrase}
                  onChange={(event) => setResetPhrase(event.target.value)}
                />
              </div>
            </div>
            <div className="modal-actions">
              <button
                type="button"
                className="text-link"
                onClick={cancelFactoryReset}
              >
                Cancel
              </button>
              <button
                type="button"
                className="text-btn"
                disabled={!canFactoryReset}
                onClick={confirmFactoryReset}
              >
                Reset
              </button>
            </div>
          </div>
        </ModalShell>
      ) : null}
      {pendingStartConfirm ? (
        <ModalShell onClose={cancelStartConfirm} stacked>
          <div
            className="modal create-entry-modal"
            role="dialog"
            aria-modal="true"
            aria-labelledby="start-confirm-title"
            aria-describedby="start-confirm-copy"
          >
            <header className="modal-head">
              <h2 id="start-confirm-title" className="modal-title">
                {pendingStartConfirm === "later"
                  ? "New date is later than previous."
                  : "New date is earlier than previous."}
              </h2>
              <button
                type="button"
                className="icon-btn modal-close"
                aria-label="Close"
                onClick={cancelStartConfirm}
              >
                <svg
                  width="18"
                  height="18"
                  viewBox="0 0 24 24"
                  fill="none"
                  aria-hidden="true"
                >
                  <path
                    d="M6 6l12 12M18 6 6 18"
                    stroke="currentColor"
                    strokeWidth="2.1"
                    strokeLinecap="round"
                  />
                </svg>
              </button>
            </header>
            <p id="start-confirm-copy" className="modal-copy">
              {pendingStartConfirm === "later"
                ? "Any entries earlier than the new start date will be hidden from the Archive, Overview, Search, and ChiveBot."
                : "Any entries from the new start date that were hidden will be visible again in the Archive, Overview, Search, and ChiveBot."}
              <br />
              <br />
              Are you sure you want to continue?
            </p>
            <div className="modal-actions">
              <button
                type="button"
                className="text-link"
                onClick={cancelStartConfirm}
              >
                Cancel
              </button>
              <button
                type="button"
                className="text-btn"
                onClick={confirmStartChange}
              >
                Yes, Continue
              </button>
            </div>
          </div>
        </ModalShell>
      ) : null}
      {pendingAutogenerateConfirm ? (
        <ModalShell onClose={cancelAutogenerateConfirm} stacked>
          <div
            className="modal create-entry-modal"
            role="dialog"
            aria-modal="true"
            aria-labelledby="autogenerate-confirm-title"
            aria-describedby="autogenerate-confirm-copy"
          >
            <header className="modal-head">
              <h2 id="autogenerate-confirm-title" className="modal-title">
                {pendingAutogenerateConfirm === "later"
                  ? "New date is later than previous."
                  : settings.autogenerateStartDate
                    ? "New date is earlier than previous."
                    : "New date is earlier than today."}
              </h2>
              <button
                type="button"
                className="icon-btn modal-close"
                aria-label="Close"
                onClick={cancelAutogenerateConfirm}
              >
                <svg
                  width="18"
                  height="18"
                  viewBox="0 0 24 24"
                  fill="none"
                  aria-hidden="true"
                >
                  <path
                    d="M6 6l12 12M18 6 6 18"
                    stroke="currentColor"
                    strokeWidth="2.1"
                    strokeLinecap="round"
                  />
                </svg>
              </button>
            </header>
            <p id="autogenerate-confirm-copy" className="modal-copy">
              {pendingAutogenerateConfirm === "later"
                ? " Empty daily entries will be created after this new date through today based on each organization's Date Active, beginning from Archive Start if they do not already exist."
                : "Empty daily entries will be created from this date through today based on each organization's Date Active, beginning from Archive Start if they do not already exist."}
              <br />
              <br />
              Are you sure you want to continue?
            </p>
            <div className="modal-actions">
              <button
                type="button"
                className="text-link"
                onClick={cancelAutogenerateConfirm}
              >
                Cancel
              </button>
              <button
                type="button"
                className="text-btn"
                onClick={confirmAutogenerateChange}
              >
                Yes, Continue
              </button>
            </div>
          </div>
        </ModalShell>
      ) : null}
    </div>
  );
}
