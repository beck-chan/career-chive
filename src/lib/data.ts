export type Org = {
  id: string;
  name: string;
  dateActive: string;
  dateInactive: string;
  hidden: boolean;
  autoGenerateDays: number[];
};

export type OrgSort = "new" | "old" | "az" | "za";

export type OrgStatusFilter = "all" | "active" | "inactive";

export function orgMatchesStatus(
  org: Org,
  status: OrgStatusFilter,
  today = TODAY,
) {
  // Date Inactive is the first day outside the window, so that day is already Inactive.
  if (status === "active") {
    return (
      Boolean(org.dateActive) &&
      (!org.dateInactive || today < org.dateInactive)
    );
  }
  if (status === "inactive") {
    return Boolean(org.dateInactive) && today >= org.dateInactive;
  }
  return true;
}

export function filterOrgList(
  orgs: Org[],
  {
    showHidden = false,
    orgStatus = "all",
    today = TODAY,
  }: { showHidden?: boolean; orgStatus?: OrgStatusFilter; today?: string },
) {
  return orgs.filter((org) => {
    if (!showHidden && org.hidden) return false;
    return orgMatchesStatus(org, orgStatus, today);
  });
}

export function sortOrgs(orgs: Org[], sortOrder: OrgSort): Org[] {
  return [...orgs].sort((a, b) => {
    if (sortOrder === "az" || sortOrder === "za") {
      const compare = a.name.localeCompare(b.name, undefined, {
        sensitivity: "base",
      });
      return sortOrder === "az" ? compare : -compare;
    }
    const aDate = a.dateActive || a.dateInactive || "";
    const bDate = b.dateActive || b.dateInactive || "";
    const compare = aDate.localeCompare(bDate);
    return sortOrder === "old" ? compare : -compare;
  });
}

