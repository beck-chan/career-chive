export const DEFAULT_TIMEZONE = "UTC";

export function normalizeTimeZone(value: string | null | undefined) {
  const tz = value?.trim() || DEFAULT_TIMEZONE;
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: tz }).format(new Date());
    return tz;
  } catch {
    return DEFAULT_TIMEZONE;
  }
}

function isValidTimeZone(value: string) {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: value }).format(new Date());
    return true;
  } catch {
    return false;
  }
}

function timeZoneOffsetPrefix(timeZone: string) {
  return timeZone === "GMT" ? "GMT" : "UTC";
}

function timeZoneOffsetMinutes(label: string) {
  const match = /(?:UTC|GMT)([+-])(\d{2}):(\d{2})/.exec(label);
  if (!match) return 0;
  const sign = match[1] === "-" ? -1 : 1;
  return sign * (Number(match[2]) * 60 + Number(match[3]));
}

function timeZoneOffsetLabel(timeZone: string, now: Date) {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    timeZoneName: "longOffset",
  }).formatToParts(now);
  const raw = parts.find((part) => part.type === "timeZoneName")?.value ?? "GMT";
  let offset = raw.replace(/^(UTC|GMT)/, "");
  if (!offset || offset === "GMT" || offset === "UTC") offset = "+00:00";
  if (!/^[+-]\d{2}:\d{2}$/.test(offset)) offset = "+00:00";
  return `${timeZoneOffsetPrefix(timeZone)}${offset}`;
}

function timeZoneLongName(timeZone: string, now: Date) {
  if (timeZone === "UTC") return "Coordinated Universal Time";
  if (timeZone === "GMT") return "Greenwich Mean Time";
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    timeZoneName: "long",
  }).formatToParts(now);
  return (
    parts.find((part) => part.type === "timeZoneName")?.value ||
    timeZone.replace(/_/g, " ")
  );
}

export function timeZoneSelectLabel(timeZone: string, now = new Date()) {
  const tz = normalizeTimeZone(timeZone);
  return `${timeZoneOffsetLabel(tz, now)} (${timeZoneLongName(tz, now)})`;
}

export function timeZoneOptions(now = new Date()) {
  const extra = [
    DEFAULT_TIMEZONE,
    "UTC",
    "GMT",
    "America/New_York",
    "America/Chicago",
    "America/Denver",
    "America/Los_Angeles",
    "Europe/London",
    "Europe/Paris",
    "Asia/Tokyo",
    "Australia/Sydney",
  ];
  let list = extra;
  try {
    const supported = Intl.supportedValuesOf("timeZone");
    if (supported.length) list = [...supported];
  } catch {
    /* Intl.supportedValuesOf is missing in some runtimes */
  }
  const lead = ["UTC", "GMT"].filter(isValidTimeZone);
  const preferred = [DEFAULT_TIMEZONE].filter(
    (zone) => zone !== "UTC" && zone !== "GMT" && isValidTimeZone(zone),
  );
  const rest = list.filter(
    (zone) =>
      zone !== "UTC" &&
      zone !== "GMT" &&
      zone !== DEFAULT_TIMEZONE &&
      isValidTimeZone(zone),
  );
  const seen = new Set<string>();
  const unique: string[] = [];
  for (const zone of [...lead, ...preferred, ...rest]) {
    const label = timeZoneSelectLabel(zone, now);
    if (seen.has(label)) continue;
    seen.add(label);
    unique.push(zone);
  }
  const head = unique.filter((zone) => zone === "UTC" || zone === "GMT");
  const tail = unique
    .filter((zone) => zone !== "UTC" && zone !== "GMT")
    .sort((a, b) => {
      const labelA = timeZoneSelectLabel(a, now);
      const labelB = timeZoneSelectLabel(b, now);
      const offset = timeZoneOffsetMinutes(labelA) - timeZoneOffsetMinutes(labelB);
      return offset || labelA.localeCompare(labelB);
    });
  return [...head, ...tail];
}

export function todayIso(
  now = new Date(),
  timeZone: string | null | undefined = DEFAULT_TIMEZONE,
) {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: normalizeTimeZone(timeZone),
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(now);
  const year = parts.find((part) => part.type === "year")?.value ?? "0000";
  const month = parts.find((part) => part.type === "month")?.value ?? "01";
  const day = parts.find((part) => part.type === "day")?.value ?? "01";
  return `${year}-${month}-${day}`;
}

