export function orgNameSlug(name: string) {
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "org";
}

export function randomOrgSuffix() {
  let suffix = "";
  while (suffix.length < 5) {
    suffix += Math.random().toString(36).slice(2);
  }
  return suffix.slice(0, 5);
}

export function newOrganizationId(name: string) {
  return `org_${orgNameSlug(name)}_${randomOrgSuffix()}`;
}

export function orgNameInUse(name: string, orgs: Org[]) {
  const needle = name.trim().toLowerCase();
  if (!needle) return false;
  return orgs.some((org) => org.name.trim().toLowerCase() === needle);
}

