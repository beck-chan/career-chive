export function isBlankDay(day: DayEntry | undefined) {
  if (!day) return true;
  if (day.attendance || day.rating) return false;
  if (day.notes.trim() || day.comments.trim()) return false;
  if (day.work.some((row) => row.title.trim() || row.description.trim() || row.link.trim())) {
    return false;
  }
  if (
    day.artifacts.some(
      (row) =>
        row.title.trim() ||
        row.url.trim() ||
        row.attachment.trim() ||
        row.attachmentKey.trim(),
    )
  ) {
    return false;
  }
  return true;
}

export function formatDayTitle(iso: string) {
  const date = new Date(`${iso}T12:00:00Z`);
  const weekday = new Intl.DateTimeFormat("en-US", {
    weekday: "short",
    timeZone: "UTC",
  }).format(date);
  const rest = new Intl.DateTimeFormat("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
    timeZone: "UTC",
  }).format(date);
  const [month, day, year] = rest.replace(",", "").split(" ");
  return `${weekday} / ${year} ${month} ${day}`;
}

export function formatLongDate(iso: string) {
  if (!iso) return "";
  return new Intl.DateTimeFormat("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${iso}T12:00:00Z`));
}

export function addMonths(isoYear: number, isoMonth: number, delta: number) {
  const index = isoYear * 12 + (isoMonth - 1) + delta;
  const year = Math.floor(index / 12);
  const month = (index % 12) + 1;
  return { year, month };
}

export function monthLabel(year: number, month: number) {
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(Date.UTC(year, month - 1, 1)));
}

export function daysInMonth(year: number, month: number) {
  return new Date(Date.UTC(year, month, 0)).getUTCDate();
}

export function isoDate(year: number, month: number, day: number) {
  return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

export function shiftIso(iso: string, days: number) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!match) return iso;
  const date = new Date(
    Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])),
  );
  date.setUTCDate(date.getUTCDate() + days);
  return isoDate(
    date.getUTCFullYear(),
    date.getUTCMonth() + 1,
    date.getUTCDate(),
  );
}

export function isOnOrAfterDateInactive(iso: string, dateInactive = "") {
  return Boolean(iso && dateInactive && iso >= dateInactive);
}

export const BEFORE_ARCHIVE_START_MESSAGE =
  "Cannot create an entry before the archive start date.";
export const BEFORE_DATE_ACTIVE_MESSAGE =
  "Cannot create an entry before the organization date active.";
export const AFTER_DATE_INACTIVE_MESSAGE =
  "Cannot create an entry on or after the organization date inactive.";
export const FUTURE_DATE_MESSAGE = "Cannot create an entry in the future.";

export function visibleArchiveStart(archiveStartDate: string) {
  return archiveStartDate || "";
}

export function isBeforeArchiveStart(iso: string, archiveStartDate: string) {
  const start = visibleArchiveStart(archiveStartDate);
  return Boolean(iso && start && iso < start);
}

export function loggingWindow(
  archiveStartDate: string,
  dateActive = "",
  dateInactive = "",
  today = TODAY,
) {
  // Outer bounds first: Archive Start (today if unset) through today.
  // A start after timezone today is still that date (empty window until it
  // arrives); timezone save does not rewrite it.
  // Date Active is not floored to Archive Start. The job may have started
  // earlier than this archive; logging still begins at the later of the two.
  // Date Inactive is exclusive. Date Active Oct 20 through Date Inactive
  // Oct 29 includes Oct 20–28 only.
  const globalMin = visibleArchiveStart(archiveStartDate) || today;
  const globalMax = today;
  const minIso = dateActive && dateActive > globalMin ? dateActive : globalMin;
  const inactiveEnd = dateInactive ? shiftIso(dateInactive, -1) : "";
  const maxIso =
    inactiveEnd && inactiveEnd < globalMax ? inactiveEnd : globalMax;
  return { minIso, maxIso, untilIso: maxIso };
}

export function orgRange(org: Org, archiveStartDate: string, today = TODAY) {
  if (!org.dateActive) {
    return { minIso: today, maxIso: "", untilIso: "" };
  }
  return loggingWindow(
    archiveStartDate,
    org.dateActive,
    org.dateInactive,
    today,
  );
}

export function createDayBlockReason(
  iso: string,
  archiveStartDate: string,
  dateActive = "",
  dateInactive = "",
  today = TODAY,
) {
  if (!iso) return "Could not create an entry.";
  if (iso > today) return FUTURE_DATE_MESSAGE;
  const start = visibleArchiveStart(archiveStartDate);
  if (start && iso < start) {
    return BEFORE_ARCHIVE_START_MESSAGE;
  }
  if (!start && iso < today) return BEFORE_ARCHIVE_START_MESSAGE;
  if (!dateActive || iso < dateActive) return BEFORE_DATE_ACTIVE_MESSAGE;
  if (isOnOrAfterDateInactive(iso, dateInactive)) {
    return AFTER_DATE_INACTIVE_MESSAGE;
  }
  const { minIso, maxIso } = loggingWindow(
    archiveStartDate,
    dateActive,
    dateInactive,
    today,
  );
  if (iso < minIso || iso > maxIso) return BEFORE_ARCHIVE_START_MESSAGE;
  return null;
}

export function isCreatableDay(
  iso: string,
  archiveStartDate: string,
  dateActive = "",
  dateInactive = "",
  today = TODAY,
) {
  return (
    createDayBlockReason(
      iso,
      archiveStartDate,
      dateActive,
      dateInactive,
      today,
    ) == null
  );
}

export function clampIsoToWindow(iso: string, minIso: string, maxIso: string) {
  if (minIso > maxIso) return maxIso;
  if (iso < minIso) return minIso;
  if (iso > maxIso) return maxIso;
  return iso;
}

export function unavailableDayLabel(
  iso: string,
  archiveStartDate: string,
  dateActive = "",
  dateInactive = "",
  today = TODAY,
) {
  if (iso > today) return undefined;
  const start = visibleArchiveStart(archiveStartDate);
  if (start && iso < start) return "Before Archive Start";
  if (!start && iso < today) return "Before Archive Start";
  if (!dateActive || iso < dateActive) return "Before Date Active";
  if (isOnOrAfterDateInactive(iso, dateInactive)) return "On or after Date Inactive";
  return "Before Archive Start";
}

