#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import {
  createCipheriv,
  createHash,
  randomBytes,
  scrypt as scryptCb,
} from "node:crypto";
import { promisify } from "node:util";
import { existsSync, readFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const packageRoot = realpathSync.native(
  fileURLToPath(new URL("..", import.meta.url)),
);

function loadEnvLocal(file) {
  if (!existsSync(file)) return;
  const text = readFileSync(file, "utf8").replace(/^\uFEFF/, "");
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim().replace(/^export\s+/, "");
    if (process.env[key]?.trim()) continue;
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

loadEnvLocal(path.join(process.cwd(), ".env.local"));
loadEnvLocal(path.join(packageRoot, ".env.local"));

function usage(exit = true) {
  console.error("Usage: npx career-chive login");
  if (exit) process.exit(1);
}

// Same parameters as src/lib/password.ts (scrypt$salt$key, 16-byte salt, 64-byte key).
const scrypt = promisify(scryptCb);
const SALT_LEN = 16;
const KEY_LEN = 64;

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

async function hashPassword(password) {
  const salt = randomBytes(SALT_LEN);
  const key = /** @type {Buffer} */ (await scrypt(password, salt, KEY_LEN));
  return `scrypt$${salt.toString("base64url")}$${key.toString("base64url")}`;
}

function encryptPassword(password) {
  const secret = process.env.SESSION_SECRET?.trim();
  if (!secret || !password) return null;
  const key = createHash("sha256").update(secret).digest();
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const ciphertext = Buffer.concat([
    cipher.update(password, "utf8"),
    cipher.final(),
  ]);
  const tag = cipher.getAuthTag();
  return `aes256gcm$${iv.toString("base64url")}$${ciphertext.toString("base64url")}$${tag.toString("base64url")}`;
}

function releaseStdin() {
  input.removeAllListeners("data");
  if (input.isTTY && input.isRaw) input.setRawMode(false);
  input.pause();
}

async function askHidden(prompt) {
  return new Promise((resolve, reject) => {
    output.write(prompt);
    const wasRaw = input.isRaw;
    if (input.isTTY) input.setRawMode(true);
    input.resume();
    input.setEncoding("utf8");
    let value = "";
    function finish(next) {
      input.off("data", onData);
      if (input.isTTY) input.setRawMode(Boolean(wasRaw));
      input.pause();
      output.write("\n");
      next();
    }
    function onData(char) {
      if (char === "\u0003") {
        finish(() => reject(new Error("Cancelled.")));
        return;
      }
      if (char === "\n" || char === "\r" || char === "\u0004") {
        finish(() => resolve(value));
        return;
      }
      if (char === "\u0008" || char === "\u007f") {
        value = value.slice(0, -1);
        return;
      }
      value += char;
    }
    input.on("data", onData);
  });
}

async function login() {
  const outDir = path.join(process.cwd(), "scripts");
  await mkdir(outDir, { recursive: true });
  const outFile = path.join(outDir, "login.sql");
  const rl = createInterface({ input, output });
  let username = "";
  let password = "";
  try {
    username = (await rl.question("Username: ")).trim();
    if (!username) {
      throw new Error("Username is required.");
    }
    rl.pause();
    password = await askHidden("Password: ");
    if (!password) {
      throw new Error("Password is required.");
    }
    const confirm = await askHidden("Confirm password: ");
    if (password !== confirm) {
      throw new Error("Passwords do not match.");
    }
  } finally {
    rl.close();
    releaseStdin();
  }

  const hash = await hashPassword(password);
  const encrypted = encryptPassword(password);
  const sql = encrypted
    ? `-- Generated by npx career-chive login. Paste in the Supabase SQL editor.
-- Singleton public.settings row (id = 1). Does not insert a second row.

insert into public.settings (id, username, password_hash, password_encrypted)
values (
  1,
  ${sqlString(username)},
  ${sqlString(hash)},
  ${sqlString(encrypted)}
)
on conflict (id) do update
set
  username = excluded.username,
  password_hash = excluded.password_hash,
  password_encrypted = excluded.password_encrypted;
`
    : `-- Generated by npx career-chive login. Paste in the Supabase SQL editor.
-- Singleton public.settings row (id = 1). Does not insert a second row.
-- SESSION_SECRET was missing, so password_encrypted is left null.
-- First Settings → Update Login fills the reversible copy.

insert into public.settings (id, username, password_hash)
values (
  1,
  ${sqlString(username)},
  ${sqlString(hash)}
)
on conflict (id) do update
set
  username = excluded.username,
  password_hash = excluded.password_hash;
`;

  await writeFile(outFile, sql, "utf8");
  console.log("Wrote scripts/login.sql");
  if (!encrypted) {
    console.log(
      "SESSION_SECRET missing; password_encrypted left null. First Settings → Update Login fills it.",
    );
  }
  console.log("Paste that file in the Supabase SQL editor.");
}

const command = process.argv[2]?.trim();
if (command !== "login") {
  usage();
}

try {
  await login();
  process.exit(0);
} catch (error) {
  releaseStdin();
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
